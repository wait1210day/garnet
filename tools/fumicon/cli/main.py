"""Command-line interface entry point for Fumicon."""

from __future__ import annotations

import argparse
import asyncio
import sys
from collections.abc import Sequence

from fumicon.core.client import FumiClient
from fumicon.core.metadata import FirmwareMetadata
from fumicon.core.models import (
    Channel,
    PanicEnded,
    PanicStarted,
    PanicText,
    RawFrame,
)
from fumicon.core.protocol import ProtocolError, decode_log
from fumicon.core.transport import (
    InputStream,
    SerialUnavailableError,
    open_input_stream,
    open_serial,
)
from fumicon.core.wire import StreamParser

from .console import ConsoleUnavailableError, run_interactive_console
from .terminal import Terminal


def run_capture_replay(
    stream: InputStream, metadata: FirmwareMetadata, terminal: Terminal
) -> int:
    """Read an offline binary capture file or stdin and print formatted logs."""
    parser = StreamParser()
    while True:
        chunk = stream.read(4096)
        if not chunk:
            break
        for event in parser.feed(chunk):
            if isinstance(event, RawFrame):
                if event.channel == Channel.LOG:
                    try:
                        record = decode_log(event, metadata)
                        terminal.print_log(record)
                    except ProtocolError as exc:
                        terminal.diagnostic(f"cannot decode log: {exc}")
            elif isinstance(event, (PanicStarted, PanicText, PanicEnded)):
                terminal.print_panic(event)
            elif isinstance(event, ProtocolError):
                terminal.diagnostic(f"protocol error in stream: {event}")

    for event in parser.finish():
        if isinstance(event, ProtocolError):
            terminal.diagnostic(f"stream EOF error: {event}")
    return 0


async def run_live_client(
    port: str,
    baud: int,
    metadata: FirmwareMetadata,
    terminal: Terminal,
    interactive: bool,
) -> int:
    """Connect to live device, execute handshake, and run console or streaming."""
    with open_serial(port, baud) as stream:
        async with FumiClient(stream, metadata) as client:
            try:
                device = await client.handshake()
            except (TimeoutError, ValueError) as exc:
                terminal.diagnostic(f"handshake failed: {exc}")
                return 1

            terminal.print(
                f"Connected to {device.name} ({device.description})\n"
                f"Build ID: {device.build_id.hex()}\n"
            )

            if interactive:
                return await run_interactive_console(client, terminal)

            # Non-interactive mode: just stream logs
            client.add_log_listener(terminal.print_log)
            client.add_panic_listener(terminal.print_panic)
            client.add_diagnostic_listener(terminal.diagnostic)

            terminal.print("Streaming logs (Press Ctrl-C to stop)...")
            try:
                while True:
                    await asyncio.sleep(1.0)
            except asyncio.CancelledError:
                return 0


def main(argv: Sequence[str] | None = None) -> int:
    """Parse CLI arguments and launch live session or offline capture replay."""
    parser = argparse.ArgumentParser(
        prog="fumicon",
        description="Fumi protocol host console and binary log decoder.",
    )
    source_group = parser.add_mutually_exclusive_group(required=True)
    source_group.add_argument(
        "--port", "-p", help="serial device (e.g. /dev/ttyUSB0 or COM3)"
    )
    source_group.add_argument(
        "--input", "-i", help="binary capture file, or '-' for stdin"
    )

    parser.add_argument(
        "--metadata",
        "-m",
        help="path to metadata JSON generated by gen_fumicon_json.py",
    )
    parser.add_argument(
        "--baud",
        "-b",
        type=int,
        default=115200,
        help="serial baud rate (default: 115200)",
    )
    parser.add_argument(
        "--color",
        choices=("auto", "always", "never"),
        default="auto",
        help="ANSI terminal color output (default: auto)",
    )
    parser.add_argument(
        "--interactive",
        action=argparse.BooleanOptionalAction,
        default=None,
        help="interactive REPL console (default: enabled when attached to a TTY)",
    )

    args = parser.parse_args(argv)

    use_color = (
        args.color == "always"
        or (args.color == "auto" and sys.stdout.isatty())
    )
    terminal = Terminal(color=use_color)

    metadata = FirmwareMetadata()
    if args.metadata is not None:
        try:
            metadata.load_file(args.metadata)
        except (OSError, ValueError) as exc:
            terminal.diagnostic(f"failed to load metadata: {exc}")
            return 1
    elif args.port is not None:
        terminal.diagnostic(
            "warning: running live session without --metadata; strings will not be resolved."
        )

    if args.input is not None:
        with open_input_stream(path=args.input) as stream:
            return run_capture_replay(stream, metadata, terminal)

    interactive = args.interactive
    if interactive is None:
        interactive = sys.stdin.isatty() and sys.stdout.isatty()

    try:
        return asyncio.run(
            run_live_client(
                port=args.port,
                baud=args.baud,
                metadata=metadata,
                terminal=terminal,
                interactive=interactive,
            )
        )
    except KeyboardInterrupt:
        return 130
    except (SerialUnavailableError, ConsoleUnavailableError) as exc:
        terminal.diagnostic(str(exc))
        return 2
    except (OSError, ValueError, TimeoutError) as exc:
        terminal.diagnostic(f"error: {exc}")
        return 1


if __name__ == "__main__":
    sys.exit(main())
